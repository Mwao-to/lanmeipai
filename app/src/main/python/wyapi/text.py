from __future__ import annotations


def size_formate(size: int | float) -> str:
    """字节数 → 人类可读,如 3.5 MB"""
    if size is None:
        return ''
    size = float(size)
    units = ['B', 'KB', 'MB', 'GB', 'TB']
    i = 0
    while size >= 1024 and i < len(units) - 1:
        size /= 1024
        i += 1
    return f'{size:.2f} {units[i]}'


def format_play_time(seconds) -> str:
    """秒 → mm:ss"""
    if seconds is None:
        return '00:00'
    seconds = int(seconds)
    m = seconds // 60
    s = seconds % 60
    return f'{m:02d}:{s:02d}'


def date_format(timestamp_ms, fmt: str = 'YYYY-MM-DD') -> str:
    """毫秒时间戳 → 日期字符串。支持 YYYY MM DD HH mm ss 占位符"""
    import time
    ts = timestamp_ms / 1000 if timestamp_ms > 1e11 else timestamp_ms
    t = time.localtime(ts)
    mapping = {
        'YYYY': f'{t.tm_year:04d}',
        'MM': f'{t.tm_mon:02d}',
        'DD': f'{t.tm_mday:02d}',
        'HH': f'{t.tm_hour:02d}',
        'mm': f'{t.tm_min:02d}',
        'ss': f'{t.tm_sec:02d}',
    }
    out = fmt
    for k, v in mapping.items():
        out = out.replace(k, v)
    return out


def format_play_count(count) -> str:
    """播放量 → 万/亿"""
    try:
        count = int(count)
    except (TypeError, ValueError):
        return ''
    if count >= 100000000:
        return f'{count / 100000000:.1f}亿'
    if count >= 10000:
        return f'{count / 10000:.1f}万'
    return str(count)


def decode_name(name: str) -> str:
    """URL 解码(容错)"""
    from urllib.parse import unquote
    try:
        return unquote(name)
    except Exception:
        return name


