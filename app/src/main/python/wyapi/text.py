def to_traditional(text: str) -> str:
    """简体 → 繁体(内置常用映射)"""
    return ''.join(_S2T.get(ch, ch) for ch in text)


def to_simplified(text: str) -> str:
    """繁体 → 简体(反转映射)"""
    _T2S = {v: k for k, v in _S2T.items()}
    return ''.join(_T2S.get(ch, ch) for ch in text)
